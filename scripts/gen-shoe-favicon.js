#!/usr/bin/env node
/*
 * gen-shoe-favicon.js — derives web/shoe-favicon.svg from the shoe mascot
 * (web/gallery/shoe-wear.js, the single source of truth for the artwork).
 *
 * The favicon is the same shoe, centered in a square viewBox, with a few
 * LEGIBLE wear marks (midsole grime, sole dirt, instep creases, warm patina)
 * animated slowly back and forth — clean → worn → clean — via CSS keyframes
 * with animation-direction: alternate. The remaining ~10 finer wear layers
 * stay at opacity 0: at 16–32 px they are invisible anyway.
 *
 * Rerun after any change to shoe-wear.js:  node scripts/gen-shoe-favicon.js
 *
 * Browser note: animated SVG favicons render in Chromium/Firefox; Safari
 * shows a static first frame (the clean shoe) — a graceful degrade.
 */
const fs = require("fs");
const path = require("path");

const { ShoeWear } = require(path.join(__dirname, "..", "web", "gallery", "shoe-wear.js"));

const inner = ShoeWear.SVG_MARKUP
  .replace(/^<svg[^>]*>/, "")
  .replace(/<\/svg>$/, "");

const css = `
  .w-grime,.w-dirt,.w-instep,.w-patina{animation-duration:7s;animation-timing-function:ease-in-out;animation-iteration-count:infinite;animation-direction:alternate}
  .w-grime{animation-name:sfw-a}
  .w-dirt{animation-name:sfw-b}
  .w-instep{animation-name:sfw-a}
  .w-patina{animation-name:sfw-c}
  @keyframes sfw-a{from{opacity:0}to{opacity:1}}
  @keyframes sfw-b{from{opacity:0}to{opacity:.95}}
  @keyframes sfw-c{from{opacity:0}to{opacity:.4}}
`;

// Source viewBox is 40 80 360 196 (wide); recenter in a 360×360 square:
// x' = x − 40 → 0..360, y' = y − 80 + 82 → vertically centered.
const out = `<svg xmlns="http://www.w3.org/2000/svg" width="360" height="360" viewBox="0 0 360 360">
<!-- Generated by scripts/gen-shoe-favicon.js from web/gallery/shoe-wear.js — do not edit by hand. -->
<style>${css}</style>
<g transform="translate(-40, 2)">${inner}</g>
</svg>
`;

const dest = path.join(__dirname, "..", "web", "shoe-favicon.svg");
fs.writeFileSync(dest, out);
console.log("wrote", dest, `(${out.length} bytes)`);
